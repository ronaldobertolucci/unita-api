-- Existing movements remain unassigned: do not infer operation IDs for legacy sales.
ALTER TABLE investment_transactions ADD COLUMN operation_id UUID;
ALTER TABLE investment_transactions ADD CONSTRAINT ck_investment_operation_type
    CHECK (operation_id IS NULL OR type IN ('SELL', 'TAX'));

CREATE TABLE investment_sale_operations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    operation_id UUID NOT NULL,
    asset_id BIGINT NOT NULL,
    request_payload TEXT NOT NULL,
    response_payload TEXT NOT NULL,
    CONSTRAINT uk_investment_sale_user_operation UNIQUE (user_id, operation_id),
    CONSTRAINT fk_investment_sale_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_investment_sale_asset FOREIGN KEY (asset_id) REFERENCES assets(id) ON DELETE CASCADE
);
