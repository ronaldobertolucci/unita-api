-- No historical transfer is paired by heuristics. Existing explicit payments are protected.
CREATE TABLE transfer_operations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(20) NOT NULL CHECK (type IN ('TRANSFER', 'FGTS_WITHDRAWAL')),
    source_transaction_id BIGINT NOT NULL UNIQUE,
    target_transaction_id BIGINT NOT NULL UNIQUE,
    CONSTRAINT ck_transfer_distinct CHECK (source_transaction_id <> target_transaction_id),
    CONSTRAINT fk_transfer_source FOREIGN KEY (source_transaction_id) REFERENCES transactions(id) ON DELETE RESTRICT,
    CONSTRAINT fk_transfer_target FOREIGN KEY (target_transaction_id) REFERENCES transactions(id) ON DELETE RESTRICT
);
ALTER TABLE credit_card_bills DROP CONSTRAINT fk_credit_card_bills_payment;
