CREATE TABLE recurring_bills (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 description VARCHAR(255) NOT NULL CHECK (TRIM(description) <> ''),
 expected_amount DECIMAL(15,2) CHECK (expected_amount > 0),
 frequency VARCHAR(20) NOT NULL CHECK (frequency IN ('MONTHLY','YEARLY')),
 first_due_date DATE NOT NULL,
 reminder_days_before INTEGER NOT NULL DEFAULT 3 CHECK (reminder_days_before BETWEEN 0 AND 30),
 email_enabled BOOLEAN NOT NULL DEFAULT TRUE,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 notes VARCHAR(2000),
 version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_recurring_bills_owner ON recurring_bills(user_id, active);
CREATE TABLE recurring_bill_email_reminders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 recurring_bill_id BIGINT NOT NULL REFERENCES recurring_bills(id) ON DELETE CASCADE,
 occurrence_key VARCHAR(7) NOT NULL,
 due_date DATE NOT NULL,
 scheduled_at TIMESTAMP WITH TIME ZONE NOT NULL,
 description VARCHAR(255) NOT NULL,
 expected_amount DECIMAL(15,2) CHECK (expected_amount > 0),
 status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING','PROCESSING','SENT','FAILED','CANCELLED')),
 attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
 next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
 reservation_token UUID,
 reserved_until TIMESTAMP WITH TIME ZONE,
 sent_at TIMESTAMP WITH TIME ZONE,
 recipient VARCHAR(255),
 last_error VARCHAR(100),
 CONSTRAINT uk_recurring_reminder_period UNIQUE(recurring_bill_id, occurrence_key)
);
CREATE INDEX idx_recurring_reminder_pending ON recurring_bill_email_reminders(status,next_attempt_at);
CREATE INDEX idx_recurring_reminder_reserved ON recurring_bill_email_reminders(status,reserved_until);
